class HarnessError(Exception):
    """A usage or environment problem: the harness cannot run (exit 2)."""


@dataclasses.dataclass(frozen=True)
class Case:
    """One headless capture: a scene, an env-selected route, or a scripted interaction."""

    id: str
    mode: str  # "scene" | "route" | "dataset" | "script"
    size: str
    theme: str
    at: float
    scene: str | None = None
    route: str | None = None
    dataset: str = "main"
    script: str | None = None
    use_route_env: bool = True
    env: tuple[tuple[str, str], ...] = ()
    a11y_expect: tuple[str, ...] = ()
    visible_expect: tuple[str, ...] = ()
    absent: tuple[str, ...] = ()
    min_texts: int = 6
    visible_min: int = 0
    # Scripts that mount media/avatars asynchronously can leave the element
    # tree timing-dependent while the image stays stable; such cases check the
    # pixels only.
    tree: bool = True

    @property
    def width(self) -> int:
        return int(self.size.split("x")[0])

    @property
    def height(self) -> int:
        return int(self.size.split("x")[1])

    @property
    def golden_image(self) -> bool:
        """Every mode hashes images: database captures disable remote media for determinism."""
        return True


@dataclasses.dataclass
class Context:
    matrix: dict
    matrix_path: Path
    manifest_path: Path
    binary: Path
    out: Path
    jobs: int
    timeout: float
    strict: bool
    env: dict
    matrix_sha256: str
    inputs: dict = dataclasses.field(default_factory=dict)
    databases: dict[str, Path] = dataclasses.field(default_factory=dict)

    @property
    def cli(self) -> Path:
        return self.binary.parent / "eterea-cli"


@dataclasses.dataclass
class Capture:
    case: Case
    returncode: int
    stdout: str
    stderr: str
    png: Path
    tree: Path
    elapsed: float

    @property
    def output(self) -> str:
        return (self.stdout + self.stderr).strip()


def sha256_bytes(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def sha256_file(path: Path) -> str:
    return sha256_bytes(path.read_bytes())


def load_matrix(path: Path) -> tuple[dict, str]:
    raw = path.read_bytes()
    try:
        matrix = json.loads(raw)
    except json.JSONDecodeError as error:
        raise HarnessError(f"invalid JSON in {path}: {error}")
    if matrix.get("schema") != 2:
        raise HarnessError(f"matrix schema is {matrix.get('schema')!r}; this harness expects 2")
    return matrix, sha256_bytes(raw)


def dataset_specs(matrix: dict) -> dict[str, dict]:
    specs: dict[str, dict] = {"main": {"fixture": matrix.get("main_fixture")}}
    for name, spec in (matrix.get("datasets") or {}).items():
        specs[name] = spec
    return specs


def build_cases(matrix: dict) -> list[Case]:
    expect = matrix["expect"]
    at = float(matrix["at"])
    cases: list[Case] = []

    scene_env = matrix.get("scene_env") or {}
    for scene in matrix["scenes"]:
        a11y = [expect["brand"]]
        if scene not in expect.get("scene_no_nav", []):
            a11y += expect["nav"]
        a11y += expect["scenes"][scene]
        env = tuple((key, str(value)) for key, value in (scene_env.get(scene) or {}).items())
        for size in matrix["sizes"]:
            for theme in matrix["themes"]:
                cases.append(
                    Case(
                        f"scene/{scene}/{size}/{theme}",
                        "scene",
                        size,
                        theme,
                        at,
                        scene=scene,
                        env=env,
                        a11y_expect=tuple(a11y),
                        min_texts=int(expect["scene_min_texts"][scene]),
                    )
                )

    route_size = matrix["route_size"]
    for route in matrix["routes"]:
        a11y = tuple([expect["brand"]] + expect["nav"] + expect["routes"][route])
        absent = tuple((expect.get("route_absent") or {}).get(route, []))
        for theme in matrix["themes"]:
            cases.append(
                Case(
                    f"route/{route}/{route_size}/{theme}",
                    "route",
                    route_size,
                    theme,
                    at,
                    route=route,
                    a11y_expect=a11y,
                    absent=absent,
                    min_texts=int(expect["route_min_texts"][route]),
                )
            )

    dataset_expect = expect.get("datasets") or {}
    for name, spec in (matrix.get("datasets") or {}).items():
        per_route = (dataset_expect.get(name) or {}).get("routes") or {}
        for route in spec["routes"]:
            route_expect = per_route.get(route) or {}
            a11y = tuple([expect["brand"]] + expect["nav"] + list(route_expect.get("expect", [])))
            for theme in spec.get("themes", matrix["themes"]):
                cases.append(
                    Case(
                        f"data/{name}/{route}/{spec['size']}/{theme}",
                        "dataset",
                        spec["size"],
                        theme,
                        at,
                        route=route,
                        dataset=name,
                        a11y_expect=a11y,
                        min_texts=int(route_expect.get("min_texts", 8)),
                    )
                )

    for script_case in matrix.get("script_cases") or []:
        visible = tuple(script_case.get("visible_expect", []))
        nav = expect["nav"] if script_case.get("nav", True) else []
        a11y = tuple([expect["brand"]] + nav + list(script_case.get("expect", [])))
        for theme in script_case["themes"]:
            cases.append(
                Case(
                    f"script/{script_case['id']}/{script_case['size']}/{theme}",
                    "script",
                    script_case["size"],
                    theme,
                    float(script_case.get("at", matrix["at"])),
                    route=script_case.get("route"),
                    dataset=script_case.get("dataset", "main"),
                    script=script_case["script"],
                    use_route_env=False,
                    a11y_expect=a11y,
                    visible_expect=visible,
                    absent=tuple(script_case.get("absent", [])),
                    min_texts=int(script_case.get("min_texts", 8)),
                    visible_min=int(script_case.get("min_visible_texts", len(visible))),
                    tree=bool(script_case.get("tree", True)),
                )
            )
    return cases


def capture_paths(ctx: Context, case: Case) -> tuple[Path, Path]:
    base = ctx.out / "captures" / case.id
    return base.with_suffix(".png"), base.with_suffix(".json")


def log_path(ctx: Context, case: Case) -> Path:
    return ctx.out / "logs" / (case.id.replace("/", "__") + ".log")


def clean_env(matrix: dict) -> dict:
    """The process environment without eterea switches, with driver defaults."""
    env = {key: value for key, value in os.environ.items() if not key.startswith("ETEREA_")}
    for key, value in (matrix.get("base_env") or {}).items():
        env.setdefault(key, value)
    return env


def prepare_settings(ctx: Context) -> None:
    """Isolate preferences per capture mode so host settings cannot leak in.

    Scene captures keep avatars and auto-media on: the demo deck's images are
    bundled local files, so they are deterministic. Database captures turn both
    off: route posts reference remote URLs, and whether one lands before the
    capture is a wall-clock race.
    """
    for mode, avatars, media in (("scene", True, True), ("db", False, False)):
        config = ctx.out / "config" / mode
        config.mkdir(parents=True, exist_ok=True)
        payload = {"avatars": avatars, "media": media}
        (config / "settings.json").write_text(json.dumps(payload) + "\n")


def case_env(ctx: Context, case: Case) -> dict:
    env = dict(ctx.env)
    env["ETEREA_CONFIG_DIR"] = str(ctx.out / "config" / ("scene" if case.mode == "scene" else "db"))
    env["XDG_CONFIG_HOME"] = str(ctx.out / "xdg-config" / case.mode)
    env["XDG_DATA_HOME"] = str(ctx.out / "xdg-data")
    env["XDG_CACHE_HOME"] = str(ctx.out / "xdg-cache")
    if case.mode == "scene":
        env["ETEREA_DEMO"] = "1"
    else:
        if case.dataset not in ctx.databases:
            raise HarnessError(f"dataset {case.dataset!r} was not prepared")
        env["ETEREA_HIDE_MEDIA"] = "1"
        env["ETEREA_DB"] = str(ctx.databases[case.dataset])
        if case.use_route_env and case.route:
            env["ETEREA_ROUTE"] = case.route
    for key, value in case.env:
        env[key] = value
    return env


def list_scenes(ctx: Context) -> list[str]:
    """Run `--list-scenes`; any error message aborts the run."""
    try:
        proc = subprocess.run(
            [str(ctx.binary), "--list-scenes"],
            env=ctx.env,
            capture_output=True,
            text=True,
            timeout=60,
        )
    except FileNotFoundError:
        raise HarnessError(f"binary not found: {ctx.binary}")
    except subprocess.TimeoutExpired:
        raise HarnessError(f"`{ctx.binary} --list-scenes` timed out after 60s")
    output = (proc.stdout + "\n" + proc.stderr).strip()
    names = [line.strip() for line in output.splitlines() if re.fullmatch(r"[a-z][a-z0-9_-]*", line.strip())]
    if proc.returncode != 0 or not names:
        raise HarnessError(f"`{ctx.binary} --list-scenes` failed (exit {proc.returncode}): {output[:500]}")
    return names


def run_cli(ctx: Context, verbs: list[str], data_home: Path, label: str) -> str:
    """Run the eterea CLI against an isolated XDG_DATA_HOME."""
    if not ctx.cli.is_file():
        raise HarnessError(
            f"eterea-cli not found next to the app binary: {ctx.cli} (build it with cargo build -p eterea-core)"
        )
    env = dict(ctx.env)
    env["XDG_DATA_HOME"] = str(data_home)
    env["XDG_CONFIG_HOME"] = str(ctx.out / "xdg-config" / "db")
    env["XDG_CACHE_HOME"] = str(ctx.out / "xdg-cache")
    try:
        proc = subprocess.run(
            [str(ctx.cli)] + verbs,
            env=env,
            capture_output=True,
            text=True,
            timeout=ctx.timeout,
        )
    except subprocess.TimeoutExpired:
        raise HarnessError(f"`eterea-cli {' '.join(verbs)}` timed out after {ctx.timeout:.0f}s")
    logs = ctx.out / "logs"
    logs.mkdir(parents=True, exist_ok=True)
    (logs / f"{label}.log").write_text(proc.stdout + proc.stderr)
    if proc.returncode != 0:
        raise HarnessError(
            f"`eterea-cli {' '.join(verbs)}` failed (exit {proc.returncode}): {proc.stderr.strip()[:500]}"
        )
    return proc.stdout + proc.stderr


def prepare_datasets(ctx: Context) -> None:
    """Build one isolated archive per dataset the matrix uses."""
    for name, spec in dataset_specs(ctx.matrix).items():
        data_home = ctx.out / "datasets" / name
        shutil.rmtree(data_home, ignore_errors=True)
        (data_home / "eterea").mkdir(parents=True, exist_ok=True)
        fixture = spec.get("fixture")
        if fixture:
            path = UI_DIR / fixture
            if not path.is_file():
                raise HarnessError(f"dataset {name!r}: fixture not found: {path}")
            run_cli(ctx, ["ingest", str(path)], data_home, f"ingest-{name}")
        else:
            # A fixture-less dataset keeps the schema but no bookmarks (empty history).
            run_cli(ctx, ["stats"], data_home, f"init-{name}")
        db = data_home / "eterea" / "bookmarks.db"
        if not db.is_file() or db.stat().st_size == 0:
            raise HarnessError(f"dataset {name!r}: no archive was created at {db}")
        ctx.databases[name] = db


def input_hashes(ctx: Context, all_cases: list[Case]) -> dict:
    """Hashes of everything that feeds the goldens: matrix, fixtures and scripts."""
    inputs: dict = {"matrix_sha256": ctx.matrix_sha256, "fixtures": {}, "scripts": {}}
    specs = dataset_specs(ctx.matrix)
    for name in sorted({case.dataset for case in all_cases}):
        fixture = (specs.get(name) or {}).get("fixture")
        if not fixture:
            continue
        path = UI_DIR / fixture
        if not path.is_file():
            raise HarnessError(f"fixture not found: {path}")
        inputs["fixtures"][fixture] = sha256_file(path)
    for script in sorted({case.script for case in all_cases if case.script}):
        path = UI_DIR / script
        if not path.is_file():
            raise HarnessError(f"script not found: {path}")
        inputs["scripts"][script] = sha256_file(path)
    return inputs


def capture_case(ctx: Context, case: Case) -> Capture:
    png, tree = capture_paths(ctx, case)
    png.parent.mkdir(parents=True, exist_ok=True)
    for path in (png, tree):
        path.unlink(missing_ok=True)
    cmd = [
        str(ctx.binary),
        "--snap",
        str(png),
        "--tree",
        str(tree),
        "--at",
        repr(float(case.at)),
        "--size",
        case.size,
        "--theme",
        case.theme,
        "--scale",
        str(ctx.matrix["scale"]),
    ]
    if case.mode == "scene":
        cmd += ["--scene", case.scene or ""]
    if case.script:
        cmd += ["--script", str(UI_DIR / case.script)]
    started = time.monotonic()
    try:
        proc = subprocess.run(
            cmd,
            env=case_env(ctx, case),
            capture_output=True,
            text=True,
            timeout=ctx.timeout,
        )
        returncode, stdout, stderr = proc.returncode, proc.stdout, proc.stderr
    except subprocess.TimeoutExpired as error:
        returncode = -1
        stdout = (error.stdout or b"").decode(errors="replace") if isinstance(error.stdout, bytes) else (error.stdout or "")
        stderr = f"timed out after {ctx.timeout:.0f}s"
    except OSError as error:
        returncode, stdout, stderr = -2, "", f"could not run {ctx.binary}: {error}"
    elapsed = time.monotonic() - started
    log = log_path(ctx, case)
    log.parent.mkdir(parents=True, exist_ok=True)
    log.write_text(
        f"# case: {case.id}\n# command: {' '.join(cmd)}\n# exit: {returncode}\n--- stdout ---\n{stdout}\n--- stderr ---\n{stderr}\n"
    )
    return Capture(case, returncode, stdout, stderr, png, tree, elapsed)


def png_info(path: Path, limits: dict) -> tuple[int, int, bytes]:
    try:
        raw = path.read_bytes()
    except FileNotFoundError:
        raise ValueError("no PNG was written")
    minimum = int(limits.get("min_png_bytes", 1024))
    if len(raw) < minimum:
        raise ValueError(f"PNG is {len(raw)} bytes, below the {minimum}-byte minimum")
    if raw[:8] != PNG_MAGIC:
        raise ValueError("file does not start with the PNG signature")
    if len(raw) < 24 or raw[12:16] != b"IHDR":
        raise ValueError("PNG has no IHDR header")
    width, height = struct.unpack(">II", raw[16:24])
    return width, height, raw


def walk_tree(node: dict, clipped: bool = False):
    """Yield (node, clipped-by-an-ancestor) for an accessibility tree, root first.

    `clips` is an accesskit state Rune emits for scroll views and clipped
    containers; descendants of those may legitimately extend past the window.
    """
    states = node.get("states") or []
    clipped = clipped or "clips" in states
    yield node, clipped
    for child in node.get("children") or []:
        yield from walk_tree(child, clipped)


def node_texts(node: dict) -> list[str]:
    """Every user-facing string on one node (not its descendants)."""
    texts: list[str] = []
    for key in ("name", "value", "description", "placeholder"):
        value = node.get(key)
        if isinstance(value, str) and value.strip():
            texts.append(value.strip())
    return texts


def collect_texts(node: dict) -> list[str]:
    """Every user-facing string in a subtree."""
    texts = node_texts(node)
    for child in node.get("children") or []:
        texts.extend(collect_texts(child))
    return texts


def paint_texts(document: dict) -> list[str]:
    """Visible text from the element/paint list (covers overlay layers the a11y tree omits)."""
    texts: list[str] = []
    for element in document.get("elements") or []:
        value = element.get("text")
        if isinstance(value, str) and value.strip():
            texts.append(value.strip())
    return texts


def tree_signature(document: dict) -> str:
    """Canonical signature of the parts that should never change silently.

    Excludes `t`/`anim_t` (virtual clock) so the signature tracks structure,
    copy and layout bounds, not the capture time.
    """
    payload = {
        "accessibility": document.get("accessibility"),
        "dark_system": document.get("dark_system"),
        "title": document.get("title"),
        "viewport": document.get("viewport"),
        "warnings": document.get("warnings"),
    }
    canonical = json.dumps(payload, sort_keys=True, separators=(",", ":"), ensure_ascii=False)
    return sha256_bytes(canonical.encode())


def route_element_key(document: dict) -> str | None:
    """The `route-<Name>` element key for the current route, when the view has one."""
    for element in document.get("elements") or []:
        key = element.get("key")
        if isinstance(key, str) and key.startswith("route-"):
            return key
    return None


def validate_capture(case: Case, ctx: Context) -> tuple[list[str], list[str], dict]:
    """Check one capture's files, layout, copy and geometry. Returns (errors, warnings, info)."""
    errors: list[str] = []
    warnings: list[str] = []
    info: dict = {"case": case.id}
    limits = ctx.matrix["limits"]
    tolerance = float(limits.get("px_tolerance", 1.0))
    png, tree_path = capture_paths(ctx, case)

    # --- PNG -------------------------------------------------------------
    try:
        width, height, raw = png_info(png, limits)
        info["image_sha256"] = sha256_bytes(raw)
        info["image_bytes"] = len(raw)
        info["width"], info["height"] = width, height
        if (width, height) != (case.width, case.height):
            errors.append(
                f"{case.id}: PNG is {width}x{height}, expected {case.width}x{case.height} "
                f"(--size {case.size}, --scale {ctx.matrix['scale']})"
            )
    except ValueError as error:
        errors.append(f"{case.id}: capture: {error}")

    # --- tree ------------------------------------------------------------
    if not tree_path.is_file() or tree_path.stat().st_size == 0:
        errors.append(f"{case.id}: tree JSON is missing or empty: {tree_path}")
        return errors, warnings, info
    try:
        document = json.loads(tree_path.read_text())
    except json.JSONDecodeError as error:
        errors.append(f"{case.id}: tree JSON does not parse: {error}")
        return errors, warnings, info
    if not isinstance(document, dict):
        errors.append(f"{case.id}: tree JSON is not an object")
        return errors, warnings, info

    info["tree_sha256"] = tree_signature(document)
    info["tree_nodes"] = 0

    viewport = document.get("viewport")
    viewport_width = float(case.width)
    viewport_height = float(case.height)
    if not (isinstance(viewport, list) and len(viewport) == 2):
        errors.append(f"{case.id}: tree has no viewport pair")
    else:
        viewport_width, viewport_height = float(viewport[0]), float(viewport[1])
        if abs(viewport_width - case.width) > tolerance or abs(viewport_height - case.height) > tolerance:
            errors.append(f"{case.id}: tree viewport is {viewport}, expected [{case.width}, {case.height}]")

    if document.get("title") != "eterea":
        errors.append(f"{case.id}: tree title is {document.get('title')!r}, expected 'eterea'")

    dark_system = document.get("dark_system")
    if not isinstance(dark_system, bool):
        errors.append(f"{case.id}: tree has no dark_system boolean")
    elif dark_system != (case.theme == "dark"):
        errors.append(f"{case.id}: --theme {case.theme} did not set system appearance (dark_system={dark_system})")

    banner = document.get("warnings") or []
    if banner:
        errors.append(f"{case.id}: rune reported warnings: {banner[:3]}")

    elements = document.get("elements")
    if not isinstance(elements, list) or len(elements) < int(limits.get("min_elements", 8)):
        errors.append(f"{case.id}: element list is missing or too short ({len(elements) if isinstance(elements, list) else 'none'})")
        elements = []
    else:
        for element in elements:
            rect = element.get("rect")
            if isinstance(rect, list) and len(rect) == 4 and (rect[2] < 0 or rect[3] < 0):
                errors.append(f"{case.id}: element {element.get('path', '?')!r} has negative size {rect}")
                break
        first_rect = elements[0].get("rect")
        if isinstance(first_rect, list) and len(first_rect) == 4:
            expected_rect = [0.0, 0.0, case.width, case.height]
            if any(abs(float(first_rect[i]) - expected_rect[i]) > tolerance for i in range(4)):
                warnings.append(f"{case.id}: root element rect is {first_rect}, expected {expected_rect}")

    if case.mode in ("route", "dataset") and case.route:
        expected_key = ROUTE_KEYS.get(case.route, f"route-{case.route.capitalize()}")
        actual_key = route_element_key(document)
        if actual_key != expected_key:
            errors.append(f"{case.id}: route element key is {actual_key!r}, expected {expected_key!r}")

    root = document.get("accessibility")
    if not isinstance(root, dict):
        errors.append(f"{case.id}: tree has no accessibility root")
        return errors, warnings, info

    root_bounds = root.get("bounds")
    if not (isinstance(root_bounds, list) and len(root_bounds) == 4):
        errors.append(f"{case.id}: accessibility root has no bounds")
    else:
        x, y, w, h = (float(value) for value in root_bounds)
        if w <= 0 or h <= 0:
            errors.append(f"{case.id}: accessibility root bounds are all-zero/degenerate: {root_bounds}")
        elif (
            abs(x) > tolerance
            or abs(y) > tolerance
            or abs(w - case.width) > tolerance
            or abs(h - case.height) > tolerance
        ):
            errors.append(f"{case.id}: accessibility root bounds {root_bounds} do not cover the {case.width}x{case.height} window")
        info["root_bounds"] = root_bounds

    nodes = 0
    texts: list[str] = []
    overflow: list[str] = []
    for node, clipped in walk_tree(root):
        nodes += 1
        texts.extend(node_texts(node))
        bounds = node.get("bounds")
        if not (isinstance(bounds, list) and len(bounds) == 4):
            continue
        x, y, w, h = (float(value) for value in bounds)
        if w < 0 or h < 0:
            errors.append(f"{case.id}: node {node.get('role', '?')} {node.get('name')!r} has negative size {bounds}")
            continue
        if clipped:
            continue
        outside = (
            x < -tolerance
            or y < -tolerance
            or x + w > viewport_width + tolerance
            or y + h > viewport_height + tolerance
        )
        if outside:
            overflow.append(f"{node.get('role', '?')} {node.get('name') or '(unnamed)'!r} bounds={bounds}")
    info["tree_nodes"] = nodes
    info["texts"] = len(texts)
    visible = paint_texts(document)
    info["visible_texts"] = len(visible)

    if not texts:
        errors.append(f"{case.id}: accessibility tree has no names, labels or values")
    if len(texts) < case.min_texts:
        errors.append(f"{case.id}: only {len(texts)} accessible text nodes, expected at least {case.min_texts}")

    a11y_haystack = "\n".join(texts).casefold()
    missing = [text for text in case.a11y_expect if text.casefold() not in a11y_haystack]
    if missing:
        errors.append(f"{case.id}: expected accessibility text missing: {missing[:8]}")

    visible_haystack = "\n".join(visible).casefold()
    missing_visible = [text for text in case.visible_expect if text.casefold() not in visible_haystack]
    if missing_visible:
        errors.append(f"{case.id}: expected visible text missing (paint list): {missing_visible[:8]}")
    if len(visible) < case.visible_min:
        errors.append(f"{case.id}: only {len(visible)} visible text elements, expected at least {case.visible_min}")

    combined_haystack = a11y_haystack + "\n" + visible_haystack
    leaked = [text for text in case.absent if text.casefold() in combined_haystack]
    if leaked:
        errors.append(f"{case.id}: suppressed copy leaked into the capture: {leaked[:4]}")

    if overflow:
        detail = "; ".join(overflow[: int(limits.get("max_reported_overflow", 5))])
        message = f"{case.id}: {len(overflow)} node(s) extend past the window with no clipping ancestor: {detail}"
        if ctx.strict:
            errors.append(message)
        else:
            warnings.append(message)

    return errors, warnings, info


def run_captures(cases: list[Case], ctx: Context) -> list[Capture]:
    captures: list[Capture] = []
    total = len(cases)
    started = time.monotonic()
    with concurrent.futures.ThreadPoolExecutor(max_workers=ctx.jobs) as pool:
        futures = {pool.submit(capture_case, ctx, case): case for case in cases}
        for done, future in enumerate(concurrent.futures.as_completed(futures), start=1):
            capture = future.result()
            captures.append(capture)
            status = "ok" if capture.returncode == 0 else f"FAIL (exit {capture.returncode})"
            print(f"[{done:>3}/{total}] {capture.case.id} {status} {capture.elapsed:.1f}s", flush=True)
    captures.sort(key=lambda capture: capture.case.id)
    print(f"captured {total} case(s) in {time.monotonic() - started:.1f}s with {ctx.jobs} worker(s)", flush=True)
    return captures


def run_copy_lint(cases: list[Case], ctx: Context) -> tuple[bool, str]:
    """Feed every captured accessibility and paint string through the repo copy lint."""
    texts: set[str] = set()
    for case in cases:
        _, tree_path = capture_paths(ctx, case)
        if not tree_path.is_file():
            continue
        try:
            document = json.loads(tree_path.read_text())
        except (json.JSONDecodeError, OSError):
            continue
        root = document.get("accessibility")
        if isinstance(root, dict):
            texts.update(collect_texts(root))
        texts.update(paint_texts(document))
    page = ctx.out / "captured-text.html"
    page.parent.mkdir(parents=True, exist_ok=True)
    page.write_text("<html><body>\n" + "\n".join(f"<p>{html.escape(text)}</p>" for text in sorted(texts)) + "\n</body></html>\n")
    script = ROOT / "scripts/copy-lint.py"
    if not script.is_file():
        return True, f"copy-lint not available at {script} (skipped)"
    try:
        proc = subprocess.run(
            [sys.executable, str(script), str(page)],
            cwd=ROOT,
            capture_output=True,
            text=True,
            timeout=120,
        )
    except subprocess.TimeoutExpired:
        return False, "copy-lint timed out after 120s"
    output = (proc.stdout + proc.stderr).strip()
    if proc.returncode != 0:
        return False, output
    return True, output.splitlines()[-1] if output else "ok"


def load_manifest(ctx: Context) -> dict | None:
    if not ctx.manifest_path.is_file():
        return None
    try:
        manifest = json.loads(ctx.manifest_path.read_text())
    except json.JSONDecodeError as error:
        raise HarnessError(f"invalid manifest JSON in {ctx.manifest_path}: {error}")
    if manifest.get("schema") != MANIFEST_SCHEMA:
        raise HarnessError(
            f"manifest schema is {manifest.get('schema')!r}, this harness writes {MANIFEST_SCHEMA}; run --update"
        )
    return manifest


def inputs_difference(expected: dict, actual: dict) -> list[str]:
    """Human-readable differences between manifest inputs and the current inputs."""
    diffs: list[str] = []
    if (expected or {}).get("matrix_sha256") != actual.get("matrix_sha256"):
        diffs.append("matrix.json changed")
    for section in ("fixtures", "scripts"):
        expected_section = (expected or {}).get(section) or {}
        actual_section = actual.get(section) or {}
        for key in sorted(set(expected_section) | set(actual_section)):
            if expected_section.get(key) == actual_section.get(key):
                continue
            label = key if key.startswith(f"{section}/") else f"{section}/{key}"
            if key not in expected_section:
                diffs.append(f"{label}: added since the manifest")
            elif key not in actual_section:
                diffs.append(f"{label}: no longer used")
            else:
                diffs.append(f"{label}: content changed")
    return diffs


def golden_errors(
    cases: list[Case], ctx: Context, infos: dict[str, dict], manifest: dict, check_stale: bool = True
) -> tuple[list[str], str]:
    errors: list[str] = []
    expected_cases = manifest.get("captures") or {}
    drift = inputs_difference(manifest.get("inputs") or {}, ctx.inputs)
    if drift:
        errors.append(
            "inputs changed since the golden manifest was written (" + "; ".join(drift[:6]) + "); review and run --update"
        )
    image_matches = image_total = tree_matches = 0
    for case in cases:
        expected = expected_cases.get(case.id)
        info = infos.get(case.id)
        if expected is None:
            errors.append(f"{case.id}: no golden entry in the manifest; run --update")
            continue
        if info is None:
            continue
        if case.golden_image:
            image_total += 1
            if info.get("image_sha256") is None:
                pass  # the capture itself is missing or invalid; reported above
            elif expected.get("image_sha256") == info.get("image_sha256"):
                image_matches += 1
            else:
                errors.append(
                    f"{case.id}: image hash mismatch (expected {str(expected.get('image_sha256'))[:16]}, "
                    f"got {str(info.get('image_sha256'))[:16]}; {info.get('image_bytes')} bytes); "
                    "review the visual change, then run --update"
                )
        if not case.tree:
            pass
        elif info.get("tree_sha256") is None:
            pass  # the capture itself is missing or invalid; reported above
        elif expected.get("tree_sha256") == info.get("tree_sha256"):
            tree_matches += 1
        else:
            errors.append(
                f"{case.id}: tree signature mismatch (expected {str(expected.get('tree_sha256'))[:16]}, "
                f"got {str(info.get('tree_sha256'))[:16]}; nodes {expected.get('tree_nodes')} -> {info.get('tree_nodes')}, "
                f"texts {expected.get('texts')} -> {info.get('texts')}); review the tree change, then run --update"
            )
    if not drift and check_stale:
        stale = sorted(set(expected_cases) - {case.id for case in cases})
        if stale:
            errors.append(f"manifest has {len(stale)} stale case(s) not in the matrix, e.g. {stale[0]}; run --update")
    summary = f"image {image_matches}/{image_total}, tree {tree_matches}/{len(cases)}"
    return errors, summary


def write_manifest(cases: list[Case], ctx: Context, infos: dict[str, dict]) -> None:
    captures: dict[str, dict] = {}
    for case in cases:
        info = infos.get(case.id)
        if info is None:
            raise HarnessError(f"cannot write manifest: no validated info for {case.id}")
        entry: dict = {
            "tree_sha256": info["tree_sha256"],
            "tree_nodes": info.get("tree_nodes"),
            "texts": info.get("texts"),
            "visible_texts": info.get("visible_texts"),
        }
        if case.golden_image:
            entry["image_sha256"] = info.get("image_sha256")
            entry["image_bytes"] = info.get("image_bytes")
        captures[case.id] = entry
    manifest = {
        "schema": MANIFEST_SCHEMA,
        "generated_by": "verification/ui/harness.py --update",
        "note": (
            "Run --update after an intentional UI change. Inputs hashes (matrix, fixtures, scripts) must match too. "
            "Scene captures use the demo deck; database/script captures read temp archives with remote media and "
            "avatars off, which keeps their images deterministic."
        ),
        "inputs": ctx.inputs,
        "captures": captures,
    }
    ctx.manifest_path.write_text(json.dumps(manifest, indent=2, sort_keys=True) + "\n")
    print(f"wrote {ctx.manifest_path} with {len(captures)} golden case(s)")


def print_failures(label: str, errors: list[str], limit: int = 40) -> None:
    if not errors:
        return
    print(f"\n{label}: {len(errors)} failure(s)")
    for error in errors[:limit]:
        print(f"  FAIL {error}")
    if len(errors) > limit:
        print(f"  ... and {len(errors) - limit} more")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Headless Rune UI verification harness for the eterea desktop shell.",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog=(
            "Exit codes: 0 pass, 1 verification failures, 2 usage or environment error.\n"
            "Examples:\n"
            "  python3 verification/ui/harness.py --update\n"
            "  python3 verification/ui/harness.py\n"
            "  python3 verification/ui/harness.py --verify-only --filter script/\n"
            "  python3 verification/ui/harness.py --route history\n"
            "  python3 verification/ui/harness.py --scene does-not-exist   # demonstrates the failure path\n"
        ),
    )
    parser.add_argument("--binary", type=Path, default=DEFAULT_BINARY, help=f"eterea binary (default: {DEFAULT_BINARY})")
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT, help=f"capture directory (default: {DEFAULT_OUT})")
    parser.add_argument("--matrix", type=Path, default=DEFAULT_MATRIX, help="matrix JSON")
    parser.add_argument("--manifest", type=Path, default=DEFAULT_MANIFEST, help="golden manifest JSON")
    parser.add_argument("--update", action="store_true", help="rewrite the golden manifest from fresh captures")
    parser.add_argument("--verify-only", action="store_true", help="verify captures already on disk; run no binary")
    parser.add_argument("--filter", default=None, help="only cases whose id matches this regular expression")
    parser.add_argument("--scene", default=None, help="only this scene (validated against --list-scenes)")
    parser.add_argument("--route", default=None, help="only this route (route and dataset cases)")
    parser.add_argument("--jobs", type=int, default=min(8, os.cpu_count() or 1), help="parallel captures (default: 8)")
    parser.add_argument("--timeout", type=float, default=180.0, help="per-capture timeout in seconds")
    parser.add_argument("--strict", action="store_true", help="treat clipping findings as failures")
    parser.add_argument("--no-copy-lint", action="store_true", help="skip the copy-lint check")
    parser.add_argument("--list", action="store_true", help="print the capture matrix and exit")
    args = parser.parse_args(argv)

    try:
        if args.update and args.verify_only:
            raise HarnessError("--update and --verify-only cannot be combined")
        if args.jobs < 1:
            raise HarnessError("--jobs must be at least 1")
        matrix, matrix_sha256 = load_matrix(args.matrix)
        all_cases = build_cases(matrix)
        cases = list(all_cases)

        if args.scene is not None:
            if args.scene not in matrix["scenes"]:
                raise HarnessError(f"unknown scene {args.scene!r}: matrix scenes are {', '.join(matrix['scenes'])}")
            cases = [case for case in cases if case.mode == "scene" and case.scene == args.scene]
        if args.route is not None:
            known_routes = set(matrix["routes"]) | {
                route for spec in (matrix.get("datasets") or {}).values() for route in spec["routes"]
            }
            if args.route not in known_routes:
                raise HarnessError(f"unknown route {args.route!r}: routes are {', '.join(sorted(known_routes))}")
            cases = [case for case in cases if case.mode in ("route", "dataset") and case.route == args.route]
        if args.filter is not None:
            try:
                pattern = re.compile(args.filter)
            except re.error as error:
                raise HarnessError(f"--filter is not a valid regular expression: {error}")
            cases = [case for case in cases if pattern.search(case.id)]
        if not cases:
            raise HarnessError("the selected matrix is empty (check --filter/--scene/--route)")
        if args.update and (args.scene or args.route or args.filter):
            raise HarnessError("--update rewrites the whole manifest; it cannot be combined with a subset filter")
        if args.list:
            for case in cases:
                print(case.id)
            return 0

        args.out.mkdir(parents=True, exist_ok=True)
        env = clean_env(matrix)
        ctx = Context(
            matrix=matrix,
            matrix_path=args.matrix,
            manifest_path=args.manifest,
            binary=args.binary,
            out=args.out,
            jobs=args.jobs,
            timeout=args.timeout,
            strict=args.strict,
            env=env,
            matrix_sha256=matrix_sha256,
        )
        ctx.inputs = input_hashes(ctx, all_cases)
        print(
            f"harness: {len(cases)} case(s), binary {ctx.binary}, output {ctx.out}"
            + (" [verify-only]" if args.verify_only else "")
        )

        manifest = None if args.update else load_manifest(ctx)
        if not args.verify_only and not args.update and manifest is None:
            raise HarnessError(f"no golden manifest at {ctx.manifest_path}; run with --update first")
        if args.verify_only and manifest is None:
            raise HarnessError(f"no golden manifest at {ctx.manifest_path}; nothing to verify against")

        infos: dict[str, dict] = {}
        all_errors: list[str] = []
        all_warnings: list[str] = []

        if args.verify_only:
            for case in cases:
                errors, warnings, info = validate_capture(case, ctx)
                infos[case.id] = info
                all_errors.extend(errors)
                all_warnings.extend(warnings)
                print(f"[verify] {case.id} {'ok' if not errors else 'FAIL ' + str(len(errors))}", flush=True)
        else:
            prepare_settings(ctx)
            scenes = sorted({case.scene for case in cases if case.mode == "scene"})
            if scenes:
                available = list_scenes(ctx)
                unknown = sorted(scene for scene in scenes if scene not in set(available))
                if unknown:
                    raise HarnessError(f"unknown scene(s) {unknown}: the binary lists {', '.join(available)}")
            if any(case.mode != "scene" for case in cases):
                prepare_datasets(ctx)
            captures = run_captures(cases, ctx)
            for capture in captures:
                errors: list[str] = []
                if capture.returncode != 0:
                    errors.append(
                        f"{capture.case.id}: binary exited {capture.returncode}; stderr: {capture.stderr.strip()[:300]}"
                    )
                fatal = capture.output.lower()
                for marker in ("no scene ", "panicked at", "this build has no agent tooling", "unknown event"):
                    if marker in fatal:
                        errors.append(f"{capture.case.id}: {capture.output.strip()[:300]}")
                        break
                captured_errors, warnings, info = validate_capture(capture.case, ctx)
                errors.extend(captured_errors)
                infos[capture.case.id] = info
                all_errors.extend(errors)
                all_warnings.extend(warnings)

        if not args.no_copy_lint:
            lint_cases = [case for case in cases if capture_paths(ctx, case)[1].is_file()]
            lint_ok, lint_output = run_copy_lint(lint_cases, ctx)
            print(f"copy-lint: {'ok' if lint_ok else 'FAIL'} ({lint_output})")
            if not lint_ok:
                all_errors.append(f"copy-lint reported errors on captured text: {lint_output[:500]}")

        if all_warnings:
            print(f"\n{len(all_warnings)} clipping warning(s) (warn-only; --strict fails on these)")
            for warning in all_warnings[:10]:
                print(f"  WARN {warning}")
            if len(all_warnings) > 10:
                print(f"  ... and {len(all_warnings) - 10} more")

        case_ids = {case.id for case in cases}
        failed_cases = {error.split(":", 1)[0] for error in all_errors if error.split(":", 1)[0] in case_ids}
        print()
        if args.update:
            print_failures("capture/validation", all_errors)
            if all_errors:
                print("\nnot writing a golden manifest from a failing run")
                return 1
            write_manifest(cases, ctx, infos)
            print("PASS (golden manifest updated)")
            return 0

        full_matrix = args.filter is None and args.scene is None and args.route is None
        golden, golden_summary = golden_errors(cases, ctx, infos, manifest or {}, check_stale=full_matrix)
        all_errors.extend(golden)
        failed_cases = {error.split(":", 1)[0] for error in all_errors if error.split(":", 1)[0] in case_ids}
        print_failures("verification", all_errors)
        print(
            f"\nsummary: {len(cases) - len(failed_cases)}/{len(cases)} case(s) passed, "
            f"copy-lint {'skipped' if args.no_copy_lint else 'checked'}, "
            f"goldens {golden_summary}"
            + (f", clipping warnings {len(all_warnings)}" if all_warnings else "")
        )
        if all_errors:
            print(f"FAILED: {len(all_errors)} error(s)")
            return 1
        print("PASS")
        return 0
    except HarnessError as error:
        print(f"harness error: {error}", file=sys.stderr)
        return 2
    except KeyboardInterrupt:
        print("interrupted", file=sys.stderr)
        return 130


if __name__ == "__main__":
    sys.exit(main())
