#!/usr/bin/env python3
"""Headless Rune UI verification harness for the eterea desktop shell.

The harness drives the real `eterea` binary through Rune's agent tooling
(`--snap`, `--tree`, `--scene`, `--script`, `--size`, `--theme`, `--at`) and
checks what a headless run can observe:

  * each capture exits 0 and writes a valid, non-empty PNG and tree JSON;
  * the tree reports the requested viewport, system appearance and no rune
    warnings;
  * the accessibility root covers the window, no node has negative geometry and
    no node escapes the window unless an ancestor clips it;
  * the route's `route-<Name>` element is present and key accessibility text
    exists (brand, the eight nav labels, scene/route copy, viewer actions, media
    alt labels, carousel controls, history/export/selection copy);
  * expected copy is *not* present when it should be suppressed (e.g. raw
    `https://t.co/` links are replaced by their expanded display URL);
  * `scripts/copy-lint.py` reports no errors on the aggregated accessibility
    and paint text captured from the trees;
  * SHA-256 image hashes and canonical tree signatures match
    `verification/ui/manifest.json` (generated by `--update`), including hashes
    of the matrix, fixtures and scripts that produced them.

Capture modes:

  scene    demo mode (`ETEREA_DEMO=1`): synthetic deck, bundled local media,
           no database and no network. Scenes x sizes x themes.
  route    the main archive built from `fixtures/x-api-v2-demo.json` by
           `eterea-cli ingest`; `ETEREA_ROUTE` selects the route.
  dataset  a secondary archive: `empty` (fresh schema, no bookmarks) for the
           empty History route, `carousel` (eterea export JSON, one bookmark
           with twenty images) for the media carousel.
  script   a Rune `--script` interaction on one of the archives (export sheet
           via `e`, selection bar via `x` + `shift+j`, carousel pages via `m` +
           `Right`, key sheet via `?`, search via `/` + typing, directory filter
           via `/` on authors/topics, route back via the mouse back button).
           Keys press at fixed virtual times; captures are deterministic.
           A script case may set `"nav": false` when the interaction replaces
           the nav (search) and `"absent"` for copy that must not render.

Database-backed captures run with `ETEREA_HIDE_MEDIA=1` and avatars off in an
isolated settings dir: remote references are never fetched, so screenshots are
deterministic and no network is used. Scene captures keep the demo deck's
bundled media on.

Usage:
  python3 verification/ui/harness.py --update        rewrite the golden manifest
  python3 verification/ui/harness.py                 capture and verify goldens
  python3 verification/ui/harness.py --verify-only   verify captures already on disk
  python3 verification/ui/harness.py --filter 'script/'      run a subset
  python3 verification/ui/harness.py --route history         one route set
  python3 verification/ui/harness.py --strict        clipping findings fail too

Exit codes: 0 pass, 1 verification failures, 2 usage or environment error.

This is runtime UI validation, not a proof and not whole-app verification.
"""

